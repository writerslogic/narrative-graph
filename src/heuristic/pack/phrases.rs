/// Words that may follow the verb phrase before the object: articles and
/// possessive determiners. "to" and "with" belong to the phrases themselves.
pub(super) const PHRASE_TRAILERS: &[&str] =
    &["the", "a", "an", "his", "her", "their", "its", "our"];

const fn rule(
    phrases: &'static [&'static str],
    relation: &'static str,
    rule: &'static str,
    base: f32,
    subject: Slot,
    object: Slot,
) -> PhraseRule {
    PhraseRule {
        phrases,
        relation,
        rule,
        base,
        subject,
        object,
        passive: false,
    }
}

const fn passive(
    phrases: &'static [&'static str],
    relation: &'static str,
    rule: &'static str,
    base: f32,
    subject: Slot,
    object: Slot,
) -> PhraseRule {
    PhraseRule {
        phrases,
        relation,
        rule,
        base,
        subject,
        object,
        passive: true,
    }
}

