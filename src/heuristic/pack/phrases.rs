//! The phrase-rule table: verbs and verb-plus-preposition phrases that name a
//! relation between two mentions, read as the *whole* text between them.
//!
//! IMPORTANT: a phrase rule is exact, not a substring search. After a closed
//! set of leading fillers (auxiliaries, adverbs) and trailing determiners are
//! peeled off, what remains between the mentions must equal one listed phrase.
//! "Nora met Marco" matches `meets`; "Nora met her friend Marco" does not,
//! because "her friend" is content the table does not account for. That is what
//! keeps a verb from being read across a clause that happens to contain it.

